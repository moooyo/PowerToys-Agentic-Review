// Author offline font and SVG assets from the installed dashboard dependencies.
// This script does not build, execute, or verify the product or prototype.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const directory = path.dirname(fileURLToPath(import.meta.url));
const repository = path.resolve(directory, '../../..');
const sourceDirectory = path.join(directory, 'prototype');
const require = createRequire(path.join(repository, 'apps/dashboard/package.json'));
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const iconsPackage = require('@mui/icons-material/package.json');

// Legacy placeholder names stay stable. Shell mappings match app.tsx.
// Conditional names in outcomeSummary and dynamic navigation icons are explicit.
const iconMap = {
  check: 'CheckRounded',
  eye: 'VisibilityRounded',
  'eye-off': 'VisibilityOffRounded',
  'arrow-left': 'ArrowBackRounded',
  'arrow-right': 'ArrowForwardRounded',
  'chevron-right': 'ChevronRightRounded',
  'circle-help': 'HelpOutlineRounded',
  'clipboard-check': 'AssignmentTurnedInRounded',
  'external-link': 'OpenInNewRounded',
  'git-pull-request': 'RateReviewRounded',
  inbox: 'InboxRounded',
  link: 'LinkRounded',
  'list-checks': 'PlayCircleRounded',
  'messages-square': 'ForumRounded',
  'panels-top-left': 'GridViewRounded',
  plus: 'AddRounded',
  'refresh-cw': 'RefreshRounded',
  route: 'RouteRounded',
  search: 'SearchRounded',
  'settings-2': 'TuneRounded',
  'sliders-horizontal': 'TuneRounded',
  x: 'CloseRounded',
};

const svgRegistry = {};
for (const [name, componentName] of Object.entries(iconMap)) {
  const Icon = require('@mui/icons-material/' + componentName).default;
  const markup = renderToStaticMarkup(React.createElement(Icon));
  // Keep MUI's actual vector contents; standalone SVG needs no Emotion stylesheet.
  const vector = markup.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/);
  if (!vector) throw new Error('The installed icon did not produce an SVG: ' + componentName);
  const viewBox = vector[1].match(/\bviewBox="([^"]+)"/)?.[1] || '0 0 24 24';
  svgRegistry[name] = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="' + viewBox + '" width="20" height="20" fill="currentColor" stroke="none" focusable="false" aria-hidden="true">' + vector[2] + '</svg>';
}

const generatedJavaScript = `/* Generated by generate-material-assets.mjs from @mui/icons-material ${iconsPackage.version}.
 * The SVG paths retain the installed MUI Rounded icon geometry.
 * License: vendor/material-licenses/@mui-icons-material.txt.
 */
(function () {
  'use strict';
  const sourceMap = Object.freeze(${JSON.stringify(iconMap, null, 2)});
  const icons = Object.freeze(${JSON.stringify(svgRegistry, null, 2)});
  function paintIcons(root = document) {
    for (const placeholder of root.querySelectorAll('i[data-lucide]')) {
      const name = placeholder.getAttribute('data-lucide');
      if (!Object.hasOwn(icons, name)) {
        // Keep an identifiable placeholder when a new icon has no reviewed mapping.
        placeholder.setAttribute('data-material-icon-missing', name || 'unnamed');
        if (!placeholder.textContent) placeholder.textContent = '[' + (name || 'icon') + ']';
        continue;
      }
      const template = document.createElement('template');
      template.innerHTML = icons[name];
      const svg = template.content.firstElementChild;
      for (const attribute of placeholder.attributes) {
        if (!['data-lucide', 'data-material-icon-missing', 'class'].includes(attribute.name)) {
          svg.setAttribute(attribute.name, attribute.value);
        }
      }
      svg.setAttribute('class', [placeholder.getAttribute('class'), 'ar-icon', 'ar-material-icon'].filter(Boolean).join(' '));
      svg.setAttribute('data-material-icon', sourceMap[name]);
      if ((placeholder.hasAttribute('aria-label') || placeholder.hasAttribute('aria-labelledby') || placeholder.getAttribute('role') === 'img') && !placeholder.hasAttribute('aria-hidden')) {
        svg.removeAttribute('aria-hidden');
        if (!svg.hasAttribute('role')) svg.setAttribute('role', 'img');
      }
      placeholder.replaceWith(svg);
    }
  }
  globalThis.ARMaterialAssets = Object.freeze({ paintIcons, sourceMap });
})();
`;
await writeFile(path.join(sourceDirectory, 'material-assets.js'), generatedJavaScript);

const licenseDirectory = path.join(sourceDirectory, 'vendor/material-licenses');
await mkdir(licenseDirectory, { recursive: true });
const fontDefinitions = [
  { packageName: '@fontsource/roboto', filePrefix: 'roboto', family: 'Roboto', weights: [400, 500, 700] },
  { packageName: '@fontsource/roboto-mono', filePrefix: 'roboto-mono', family: 'Roboto Mono', weights: [400] },
];
const fontRules = ['/* Embedded Latin WOFF2 assets from the installed dashboard font packages. */'];
for (const font of fontDefinitions) {
  const packageDirectory = path.dirname(require.resolve(font.packageName + '/package.json'));
  const packageInfo = JSON.parse(await readFile(path.join(packageDirectory, 'package.json'), 'utf8'));
  fontRules.push('/* ' + font.packageName + ' ' + packageInfo.version + '; license: vendor/material-licenses/' + font.packageName.replaceAll('/', '-') + '.txt */');
  for (const weight of font.weights) {
    const file = font.filePrefix + '-latin-' + weight + '-normal.woff2';
    const data = (await readFile(path.join(packageDirectory, 'files', file))).toString('base64');
    fontRules.push('@font-face {\n  font-family: "' + font.family + '";\n  font-style: normal;\n  font-weight: ' + weight + ';\n  font-display: swap;\n  src: url("data:font/woff2;base64,' + data + '") format("woff2");\n}');
  }
  await writeFile(path.join(licenseDirectory, font.packageName.replaceAll('/', '-') + '.txt'), await readFile(path.join(packageDirectory, 'LICENSE')));
}
fontRules.push('#ar-m3-prototype code, #ar-m3-prototype pre, #ar-m3-prototype .ar-publish-code { font-family: "Roboto Mono", Consolas, monospace; }');
await writeFile(path.join(sourceDirectory, 'material-fonts.css'), fontRules.join('\n\n') + '\n');
const iconDirectory = path.dirname(require.resolve('@mui/icons-material/package.json'));
await writeFile(path.join(licenseDirectory, '@mui-icons-material.txt'), await readFile(path.join(iconDirectory, 'LICENSE')));
console.log('Authored ' + Object.keys(iconMap).length + ' Material SVG mappings, four embedded font faces, and dependency license notices.');
